# Function to parse the filename and extract parameters
def parse_filename(filename: str) -> dict:
    """
    Parses a .pth experiment result filename to extract training parameters.

    The filename is expected to follow a specific pattern generated by `FL/FedAvg.py`.
    Example pattern:
    fedavg_{dataset_name}_seed{seed}_{mode}_s{n_silos}_ua{user_alpha}_sa{silo_alpha}_{is_secure}_{is_histogram_secure}_he{histogram_epsilon}_sigma{sigma}_mgn{max_grad_norm}_llr{local_learning_rate}_glr{global_learning_rate}_u{n_users}_i{iters}_e{local_epochs}.pth

    Args:
        filename (str): The path to the .pth file.

    Returns:
        dict: A dictionary containing the extracted parameters. Keys include 'dataset',
              'seed', 'mode', 'n_silos', 'user_alpha', 'silo_alpha', 'is_secure',
              'is_histogram_secure', 'histogram_epsilon', 'sigma', 'max_grad_norm',
              'local_learning_rate', 'global_learning_rate', 'n_users', 'iters',
              and 'local_epochs'. Values are parsed to their appropriate types (int, float, str).
              If a parameter cannot be found, a default value (e.g., 0, 0.0, "") is used.
    """
    basename = os.path.basename(filename)
    
    # Regex patterns to extract parameters
    patterns = {
        'dataset': r'fedavg_([^_]+)_',
        'seed': r'seed(\d+)',
        'mode': r'seed\d+_([^_]+)_s\d+', # Mode is between seed and n_silos
        'n_silos': r'_s(\d+)_', # More specific to avoid matching 'is_secure'
        'user_alpha': r'ua([\d\.]+)',
        'silo_alpha': r'sa([\d\.]+)',
        # is_secure is between silo_alpha and (is_histogram_secure or he)
        'is_secure': r'sa[\d\.]+_([^_]+)_(?:[a-zA-Z]{2}_dp|he)', # handles cases like 'uldp_dp_he' or 'uldp_he'
        'is_histogram_secure': r'sa[\d\.]+_([^_]+)_([^_]+)_he', # if is_secure is present, hist_secure is next
                                                               # This might need adjustment if is_secure is 'ndp'
                                                               # and hist_secure is also 'ndp' or empty.
        'histogram_epsilon': r'he([\d\.]+)',
        'sigma': r'sigma([\d\.]+)',
        'max_grad_norm': r'mgn([\d\.]+)',
        'local_learning_rate': r'llr([\d\.]+)',
        'global_learning_rate': r'glr([\d\.]+)',
        'n_users': r'_u(\d+)_', # More specific
        'iters': r'i(\d+)',
        'local_epochs': r'e(\d+)\.pth'
    }

    params = {}
    
    # Simpler extraction logic
    params['dataset'] = (re.search(patterns['dataset'], basename).group(1)
                         if re.search(patterns['dataset'], basename) else "")
    params['seed'] = (int(re.search(patterns['seed'], basename).group(1))
                      if re.search(patterns['seed'], basename) else 0)
    params['mode'] = (re.search(patterns['mode'], basename).group(1)
                      if re.search(patterns['mode'], basename) else "")
    # For n_silos, ensure it's not confused with other 's' like in 'is_secure'
    silos_match = re.search(r'_s(\d+)_ua', basename) # Look for _s<digits>_ua
    params['n_silos'] = int(silos_match.group(1)) if silos_match else 0

    params['user_alpha'] = (float(re.search(patterns['user_alpha'], basename).group(1))
                            if re.search(patterns['user_alpha'], basename) else 0.0)
    params['silo_alpha'] = (float(re.search(patterns['silo_alpha'], basename).group(1))
                            if re.search(patterns['silo_alpha'], basename) else 0.0)

    # is_secure and is_histogram_secure can be tricky due to optional parts
    # Example: fedavg_mnist_seed1_zipf_s5_ua0.5_sa2.0_uldp_dp_he1.0_sigma...
    # Example: fedavg_mnist_seed1_zipf_s5_ua0.5_sa2.0_ndp_he1.0_sigma... (hist_secure is empty)
    
    # Try to get is_secure first
    # It's after silo_alpha (sa<float>_) and before histogram_epsilon (he<float>) or sigma if hist_eps is absent
    # Pattern: sa<float>_(is_secure_value)_(maybe_hist_secure_value)_he<float>
    # Or:      sa<float>_(is_secure_value)_sigma<float> (if no hist_secure and no hist_epsilon)
    
    # Simplified: Assume is_secure is the segment after sa[0-9.]+
    # This might capture 'uldp_dp' or 'ndp' etc. We'll refine in generate_label
    _temp_secure_part_match = re.search(r'sa[\d\.]+_([^_]+(?:_[^_]+)?)_', basename) # Grabs one or two segments
    _temp_secure_part = _temp_secure_part_match.group(1) if _temp_secure_part_match else ""

    params['is_secure'] = _temp_secure_part # Store potentially combined field
    # is_histogram_secure will be derived in generate_label or needs more complex regex here
    # For now, leave it simple as the original logic was also basic
    params['is_histogram_secure'] = "" # Will be refined by generate_label if needed
    if "_dp_he" in _temp_secure_part or "_nf_dp_he" in _temp_secure_part or "_sf_dp_he" in _temp_secure_part:
        if "_nf_dp_he" in _temp_secure_part :
            params['is_secure'] = _temp_secure_part.split('_nf_dp_he')[0]
            params['is_histogram_secure'] = "nf_dp"
        elif "_sf_dp_he" in _temp_secure_part:
            params['is_secure'] = _temp_secure_part.split('_sf_dp_he')[0]
            params['is_histogram_secure'] = "sf_dp"
        elif "_dp_he" in _temp_secure_part:
            params['is_secure'] = _temp_secure_part.split('_dp_he')[0]
            params['is_histogram_secure'] = "dp"
    elif "_he" in _temp_secure_part : # e.g. uldp_he... means hist_secure is empty or 'ndp'
        params['is_secure'] = _temp_secure_part.split('_he')[0]
        # params['is_histogram_secure'] remains "" or could be 'ndp' if that's the default meaning

    params['histogram_epsilon'] = (float(re.search(patterns['histogram_epsilon'], basename).group(1))
                                   if re.search(patterns['histogram_epsilon'], basename) else 0.0)
    params['sigma'] = (float(re.search(patterns['sigma'], basename).group(1))
                       if re.search(patterns['sigma'], basename) else 0.0)
    params['max_grad_norm'] = (float(re.search(patterns['max_grad_norm'], basename).group(1))
                               if re.search(patterns['max_grad_norm'], basename) else 0.0)
    params['local_learning_rate'] = (float(re.search(patterns['local_learning_rate'], basename).group(1))
                                     if re.search(patterns['local_learning_rate'], basename) else 0.0)
    params['global_learning_rate'] = (float(re.search(patterns['global_learning_rate'], basename).group(1))
                                      if re.search(patterns['global_learning_rate'], basename) else 0.0)
    # For n_users, ensure it's not confused with other 'u'
    users_match = re.search(r'_u(\d+)_i\d+', basename) # Look for _u<digits>_i
    params['n_users'] = int(users_match.group(1)) if users_match else 0
    
    params['iters'] = (int(re.search(patterns['iters'], basename).group(1))
                       if re.search(patterns['iters'], basename) else 0)
    params['local_epochs'] = (int(re.search(patterns['local_epochs'], basename).group(1))
                              if re.search(patterns['local_epochs'], basename) else 0)
    return params

# Function to generate legend label based on filename
def generate_label(filename: str, params: dict) -> str:
    """
    Generates a descriptive label for plotting based on the filename and parsed parameters.

    It constructs a label string that highlights the security mode (`is_secure`),
    any histogram security (`is_histogram_secure`), and the data distribution mode.

    Args:
        filename (str): The original filename (used for some special case checks, though
                        `params` should ideally contain all necessary info).
        params (dict): A dictionary of parsed parameters from `parse_filename`.
                       Expected keys: 'is_secure', 'is_histogram_secure', 'mode'.

    Returns:
        str: A formatted label string for use in plot legends.
             Example: "ULDP-AVG-w-Hist-DP (zipf)", "ndp (uniform)".
    """
    basename = os.path.basename(filename) # Keep for direct checks if params are ambiguous
    
    # Determine the base model type from 'is_secure'
    # params['is_secure'] might be 'uldp', 'cldp', 'ndp'
    # params['is_histogram_secure'] might be 'dp', 'nf_dp', 'sf_dp', or "" (empty or 'ndp')

    model_type_base = params.get("is_secure", "unknown").upper()
    hist_secure_type = params.get("is_histogram_secure", "")

    label_parts = [model_type_base]

    if model_type_base == "ULDP": # uldp often implies an averaging step
        label_parts = ["ULDP-AVG"]


    if hist_secure_type:
        if hist_secure_type == "dp":
            label_parts.append("w-Hist-DP")
        elif hist_secure_type == "nf_dp":
            label_parts.append("w-Hist-NF-DP")
        elif hist_secure_type == "sf_dp":
            label_parts.append("w-Hist-SF-DP")
        # If hist_secure_type is 'ndp' or empty, no specific histogram DP suffix is added by default.

    final_model_type = "-".join(filter(None, label_parts))
    if not final_model_type : final_model_type = "N/A"


    # Add data distribution mode
    mode_str = ""
    data_mode = params.get("mode", "")
    if data_mode == "uniform":
        mode_str = " (uniform)"
    elif data_mode == "zipf":
        mode_str = " (zipf)"
    elif data_mode == "dirichlet":
        mode_str = " (dirichlet)"
        
    return f'{final_model_type}{mode_str}'

